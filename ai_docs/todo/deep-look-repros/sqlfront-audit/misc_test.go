package sqlfrontaudit

import "testing"

func TestMiscProbes(t *testing.T) {
	d := openDB(t)
	must(t, d, `create sequence sq`)
	must(t, d, `create table t (id int primary key, i int, s text, ts timestamp, d date, b bool)`)
	must(t, d, `insert into t values (1, 10, '5', '2024-02-29 12:00:00', '2024-02-29', true)`)
	probe(t, d,
		`select E'a\nb', length(E'\x41'), E'\x41', E'é', E'\101', E'\\', E'it\'s'`,
		`select U&'d\0061t'`,
		`select 'a\'`, `select e'tab\there'`,
		`select 'T'::regclass`, `select 'public.t'::regclass`, `select '"t"'::regclass`, `select 'pg_class'::regclass`,
		`alter table t alter column i type int using nextval('sq')`,
		`select i from t`,
		`alter table t alter column ts type date using ts::date`,
		`select ts from t`,
		`alter table t alter column d type timestamp using d::timestamp`,
		`select d from t`,
		`alter table t alter column s type int using s::int`,
		`alter table t alter column b type int using b::int`,
		`alter table t alter column b type int`,
		`alter table t add constraint ck check (nextval('sq') > 0)`,
		`insert into t (id) values (2)`,
		`create table c (id int primary key, a int check (a > 0), b text check (b in ('x','y')), c int check (c is null or c between 1 and 5), d text check (length(d) < 5), e date check (e > '2000-01-01'))`,
		`insert into c values (1, 1, 'x', null, 'abc', '2024-01-01')`,
		`insert into c values (2, 1, 'z', null, 'abc', '2024-01-01')`,
		`insert into c values (3, 1, 'x', null, 'abc', '1999-01-01')`,
		`insert into c values (4, null, null, null, null, null)`,
		`select id from c order by id`,
		`select $1`,
		`select * from t where id = 1 and`,
		`selec 1`,
		`select from t`,
		`select 1 +`,
		`select (1`,
		`select * from nope`,
		`select nope from t`,
		`select t.nope from t`,
		`select x.id from t`,
		`insert into t (id, nope) values (9, 1)`,
		`insert into t (id) values (1)`,
		`insert into t (id, i) values (10, 'abc')`,
		`insert into t (id) values (11, 12)`,
		`update t set nope = 1`,
		`select nofunc(1)`,
		`select 1 from t group by nope`,
		`select i, count(*) from t`,
		`select * from t order by 99`,
		`select sum(s) from t`,
		`select max(b), min(b), sum(b) from t`,
		`select count(*) filter (where i > 0) from t`,
		`select i, count(*) from t group by 1 having count(*) > 0 order by 2 desc`,
		`select distinct i from t order by i`,
		`select t1.id from t t1 join t t2 on t1.id = t2.id`,
		`select id from t where id = 1 or id = 2 or id in (3,4) and not (i is null)`,
		`select 1 union select 'a'`,
		`select 1 union select 1.5`,
		`select id from t where ts = now() - 1`,
	)
}
