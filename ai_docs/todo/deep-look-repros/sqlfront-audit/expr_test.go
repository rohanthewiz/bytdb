package sqlfrontaudit

import "testing"

func TestExprProbes(t *testing.T) {
	d := openDB(t)
	must(t, d, `create table t (id int primary key, i int, f float, s text, b bool, ts timestamp, d date, u uuid, j jsonb, by bytea)`)
	must(t, d, `insert into t values (1, 10, 1.5, 'héllo', true, '2024-02-29 12:00:00', '2024-02-29', 'a0eebc99-9c0b-4ef8-bb6d-6bb9bd380a11', '{"a":1}', '\x0102')`)
	must(t, d, `insert into t values (2, null, null, null, null, null, null, null, null, null)`)
	probe(t, d,
		// --- three-valued logic
		`select null and false, null and true, null or true, null or false, not null`,
		`select 1 in (1, null), 2 in (1, null), 2 not in (1, null), null in (1)`,
		`select 1 = any(null), not (1 = any(null))`,
		`select case when null then 1 else 2 end, case null when null then 1 else 2 end`,
		`select coalesce(null, null), coalesce(1, 1/0), nullif(1,1), nullif(1,2), nullif(null,1)`,
		`select 1 where null`,
		`select id from t where i = null`,
		`select id from t where not (i > 5)`,
		`select id from t where i between 5 and null`,
		`select null between 1 and 2, 1 between null and 2, 3 between null and 2`,
		`select null is null, null is not null, (1 = null) is null`,
		`select true is true, null is not true, 1 is distinct from null`,
		// --- integer arithmetic
		`select 9223372036854775807 + 1`,
		`select -9223372036854775808`,
		`select -9223372036854775808 - 1`,
		`select 9223372036854775807 * 2, 1`,
		`select (-9223372036854775807 - 1) / -1`,
		`select (-9223372036854775807 - 1) % -1`,
		`select -(-9223372036854775807 - 1)`,
		`select 7 / 2, -7 / 2, 7 % -2, -7 % 2, 7.0 / 2, 1/0`,
		`select 1 % 0, 1.0 / 0, 5.5 % 2`,
		`select 2 + 3 * 4, (2 + 3) * 4, 2 - 3 - 4, 100 / 10 / 5, - 2 * 3, 2 * - 3`,
		`select -1::int, -1::text, - 1 :: bigint`,
		`select 1 - -1, 1 - - 1, 1+-+1`,
		`select 9223372036854775808, 12345678901234567890123`,
		`select 1e308 * 10, -1e308 * 10, 1e-320 / 1e10`,
		`select 0.1 + 0.2, 1.0, 1e3, 1.50, 3.0 * 2`,
		`select 9007199254740993 = 9007199254740992.0, 9007199254740993 > 9007199254740992.0`,
		`select 9223372036854775807 = 9223372036854775807.0, 9223372036854775807 < 9223372036854775808.0`,
		// --- casts
		`select '12'::int, ' 12 '::int, '1.5'::int, 1.5::int, 2.5::int, -2.5::int, 3.5::int`,
		`select 'abc'::int`,
		`select 1e30::int`,
		`select 'nan'::float, 'inf'::float, 'infinity'::float::int`,
		`select 'NaN'::float = 'NaN'::float, 'NaN'::float > 1e308`,
		`select 70000::smallint, 3000000000::int, 3000000000::int4`,
		`select true::int, 1::bool, 0::bool, 2::bool, 'yes'::bool, 't'::bool, 'on'::bool, 'TRUE'::bool`,
		`select 1::text, 1.5::text, 1e21::text, 1000000.0::text, 1e6::text, true::text, 0.1::text`,
		`select 1e15::text, 1e16::text, 123456789.125::text, 1e-5::text`,
		`select ts::text, d::text, u::text, j::text, by::text from t where id = 1`,
		`select ts::date, d::timestamp, ts::int, d::int from t where id = 1`,
		`select now()::date = current_date`,
		`select '2024-02-29'::date, '2023-02-29'::date, '2024-13-01'::date`,
		`select '2024-02-29 25:00:00'::timestamp`,
		`select '2024-02-29T12:00:00Z'::timestamp, '2024-02-29 12:00:00+05:30'::timestamptz, '2024-02-29 12:00:00.123456789'::timestamp`,
		`select '0001-01-01'::date, '9999-12-31'::date, '294277-01-01'::timestamp, '300000-01-01'::timestamp, '4714-11-24 BC'::date`,
		`select 'epoch'::timestamp, 'infinity'::timestamp, 'today'::date, 'now'::timestamp`,
		`select 'A0EEBC99-9C0B-4EF8-BB6D-6BB9BD380A11'::uuid, '{a0eebc99-9c0b-4ef8-bb6d-6bb9bd380a11}'::uuid, 'a0eebc999c0b4ef8bb6d6bb9bd380a11'::uuid`,
		`select 'a0eebc99-9c0b-4ef8-bb6d-6bb9bd380a1'::uuid`,
		`select 'a0ee-bc99-9c0b-4ef8-bb6d-6bb9bd380a11'::uuid`,
		`select cast(1 as text), cast('5' as int)`,
		`select 1::numeric(10,2), 'x'::varchar(10), 'x'::character varying, now()::timestamp without time zone`,
		`select 1::double precision, 1::float8, '1'::int8, 1::int2`,
		`select int '5', date '2024-01-01', timestamp '2024-01-01 00:00:00'`,
		`select null::int, null::text, null::uuid`,
		`select ''::int`,
		`select '0x10'::int, '1_000'::int, '1e2'::int, '+5'::int`,
		`select '0x1p-2'::float, '1_0'::float, ''::float`,
		`select '{"a":1}'::jsonb::text, '[1, 2]'::json, 'null'::jsonb, '1'::jsonb::int`,
		// --- strings
		`select length(s), upper(s), lower('ÀÉ'), length('日本語'), char_length('👍') from t where id = 1`,
		`select length(123), upper(1), lower(null)`,
		`select 'a' || 'b', 'a' || 1, 1 || 'a', 'a' || null, 1 || 2, 'a' || 1.0, 'x' || true`,
		`select 'a' || ts, 'a' || d from t where id = 1`,
		`select length(by) from t where id = 1`,
		// --- LIKE
		`select 'abc' like 'a%', 'abc' like 'A%', 'abc' ilike 'A%', 'a%c' like 'a\%c', 'abc' like 'a\%c', 'a_c' like 'a\_c'`,
		`select 'abc' like 'abc\'`,
		`select 'a\c' like 'a\\c', 'héllo' like 'h_llo', 'héllo' like 'h__llo', 'a
b' like 'a%b', 'a.c' like 'a.c', 'abc' like 'a.c', '' like '', '' like '%', 'abc' like ''`,
		`select 'abc' like null, null like 'a', 'abc' not like 'a%'`,
		`select 'İ' ilike 'i', 'ß' ilike 'SS', 'É' ilike 'é', 'K' ilike 'K'`,
		`select 'abc' like 'a%' escape '\', 'abc' like 'a!%' escape '!'`,
		`select 'abc' ~ '^a', 'abc' ~ 'B', 'abc' ~* 'B', 'abc' !~ 'x', 'abc' ~ '(', 'abc' ~ 'a{1,5000}'`,
		`select 1 like '1'`,
		`select s like 'h%' from t`,
		`select 'abc' similar to 'a%'`,
	)
}
