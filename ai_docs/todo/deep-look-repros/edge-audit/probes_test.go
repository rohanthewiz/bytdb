package edgeaudit

import (
	"context"
	"testing"
)

// Statements popular clients and tools send at connect time or as part of
// their normal bookkeeping. Sources: the tools' own source (golang-migrate
// postgres/pgx drivers, goose dialect queries, GORM migrator, pgx, lib/pq,
// psycopg/SQLAlchemy dialect init, pgjdbc, DBeaver, pg_dump, npgsql,
// pgbouncer server_reset_query).
func TestToolProbes(t *testing.T) {
	addr, _, _ := startServer(t, nil)
	ctx := context.Background()
	c := pgxConn(t, addr)
	probes := []struct{ tool, q string }{
		{"pgx ping", "-- ping"},
		{"pgx ping", ";"},
		{"pgx/pool reset; pgbouncer; npgsql", "DISCARD ALL"},
		{"pgx", "DEALLOCATE ALL"},
		{"psql/any", "SELECT version()"},
		{"any", "SELECT current_database()"},
		{"any", "SELECT current_schema()"},
		{"any", "SELECT current_user"},
		{"any", "SELECT session_user"},
		{"any", "SELECT pg_backend_pid()"},
		{"any", "SHOW server_version"},
		{"atlas/SQLAlchemy", "SHOW server_version_num"},
		{"atlas", "SELECT current_setting('server_version_num')"},
		{"SQLAlchemy", "SHOW standard_conforming_strings"},
		{"SQLAlchemy", "SHOW transaction isolation level"},
		{"pgjdbc startup", "SET extra_float_digits = 3"},
		{"pgjdbc", "SET application_name = 'x'"},
		{"psycopg", "SET client_encoding TO 'UTF8'"},
		{"psycopg/SQLAlchemy", "SET DateStyle = 'ISO'"},
		{"pg_dump", "SELECT pg_catalog.set_config('search_path', '', false)"},
		{"pg_dump", "SET statement_timeout = 0"},
		{"pg_dump", "SET lock_timeout = 0"},
		{"pg_dump", "SET TRANSACTION ISOLATION LEVEL REPEATABLE READ, READ ONLY"},
		{"pg_dump", "SELECT pg_catalog.pg_is_in_recovery()"},
		{"golang-migrate", "SELECT CURRENT_DATABASE()"},
		{"golang-migrate", "SELECT CURRENT_SCHEMA()"},
		{"golang-migrate/goose/atlas/flyway", "SELECT pg_advisory_lock(12345)"},
		{"golang-migrate/goose", "SELECT pg_advisory_unlock(12345)"},
		{"goose (session locker)", "SELECT pg_try_advisory_lock(12345)"},
		{"atlas", "SELECT pg_try_advisory_lock(12345)"},
		{"golang-migrate", `SELECT COUNT(1) FROM information_schema.tables WHERE table_schema = 'public' AND table_name = 'schema_migrations' LIMIT 1`},
		{"golang-migrate", `CREATE TABLE IF NOT EXISTS "public"."schema_migrations" (version bigint not null primary key, dirty boolean not null)`},
		{"golang-migrate", `TRUNCATE "public"."schema_migrations"`},
		{"golang-migrate", `INSERT INTO "public"."schema_migrations" (version, dirty) VALUES (1, false)`},
		{"golang-migrate", `SELECT version, dirty FROM "public"."schema_migrations" LIMIT 1`},
		{"goose", `SELECT EXISTS ( SELECT 1 FROM pg_tables WHERE (current_schema() IS NULL OR schemaname = current_schema()) AND tablename = 'goose_db_version' )`},
		{"goose", `CREATE TABLE goose_db_version ( id integer PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY, version_id bigint NOT NULL, is_applied boolean NOT NULL, tstamp timestamp NOT NULL DEFAULT now() )`},
		{"goose", `INSERT INTO goose_db_version (version_id, is_applied) VALUES (0, true)`},
		{"goose", `SELECT version_id, is_applied FROM goose_db_version ORDER BY id DESC`},
		{"goose", `DELETE FROM goose_db_version WHERE version_id=1`},
		{"GORM HasTable", `SELECT count(*) FROM information_schema.tables WHERE table_schema = CURRENT_SCHEMA() AND table_name = 'users' AND table_type = 'BASE TABLE'`},
		{"GORM AutoMigrate", `CREATE TABLE "users" ("id" bigserial,"created_at" timestamptz,"updated_at" timestamptz,"deleted_at" timestamptz,"name" text,"age" bigint,PRIMARY KEY ("id"))`},
		{"GORM AutoMigrate", `CREATE INDEX IF NOT EXISTS "idx_users_deleted_at" ON "users" ("deleted_at")`},
		{"GORM ColumnTypes", `SELECT c.column_name, c.is_nullable = 'YES', c.udt_name, c.character_maximum_length, c.numeric_precision, c.numeric_precision_radix, c.numeric_scale, c.datetime_precision, 8 * typlen, c.column_default, pd.description, c.identity_increment FROM information_schema.columns AS c JOIN pg_type AS pgt ON c.udt_name = pgt.typname LEFT JOIN pg_catalog.pg_description as pd ON pd.objsubid = c.ordinal_position AND pd.objoid = (SELECT oid FROM pg_catalog.pg_class WHERE relname = c.table_name AND relnamespace = (SELECT oid FROM pg_catalog.pg_namespace WHERE nspname = c.table_schema)) where table_catalog = 'test' AND table_schema = CURRENT_SCHEMA() AND table_name = 'users'`},
		{"GORM", `SELECT * FROM "users" WHERE "users"."deleted_at" IS NULL ORDER BY "users"."id" LIMIT 1`},
		{"GORM Create", `INSERT INTO "users" ("created_at","updated_at","deleted_at","name","age") VALUES (now(),now(),NULL,'a',1) RETURNING "id"`},
		{"SQLAlchemy has_table", `SELECT pg_catalog.pg_class.relname FROM pg_catalog.pg_class JOIN pg_catalog.pg_namespace ON pg_catalog.pg_namespace.oid = pg_catalog.pg_class.relnamespace WHERE pg_catalog.pg_class.relname = 'users' AND pg_catalog.pg_class.relkind = ANY (ARRAY['r', 'p', 'f', 'v', 'm']) AND pg_catalog.pg_table_is_visible(pg_catalog.pg_class.oid) AND pg_catalog.pg_namespace.nspname != 'pg_catalog'`},
		{"psycopg2/SQLAlchemy hstore", `SELECT t.oid, typarray FROM pg_type t JOIN pg_namespace ns ON typnamespace = ns.oid WHERE typname = 'hstore'`},
		{"DBeaver", `SELECT current_schema(),session_user`},
		{"DBeaver", `SHOW search_path`},
		{"DBeaver", `SELECT n.oid,n.*,d.description FROM pg_catalog.pg_namespace n LEFT OUTER JOIN pg_catalog.pg_description d ON d.objoid=n.oid AND d.objsubid=0 AND d.classoid='pg_namespace'::regclass ORDER BY nspname`},
		{"DBeaver", `SELECT db.oid,db.* FROM pg_catalog.pg_database db WHERE datname='test'`},
		{"DBeaver", `select * from pg_catalog.pg_settings where name='standard_conforming_strings'`},
		{"DBeaver/pgjdbc", `SELECT typinput='array_in'::regproc as is_array, typtype, typname, pg_type.oid FROM pg_catalog.pg_type LEFT JOIN (select ns.oid as nspoid, ns.nspname, r.r from pg_namespace as ns join ( select s.r, (current_schemas(false))[s.r] as nspname from generate_series(1, array_upper(current_schemas(false), 1)) as s(r) ) as r using ( nspname ) ) as sp ON sp.nspoid = typnamespace WHERE pg_type.oid = 25 ORDER BY sp.r, pg_type.oid DESC`},
		{"pgjdbc getTables", `SELECT NULL AS TABLE_CAT, n.nspname AS TABLE_SCHEM, c.relname AS TABLE_NAME FROM pg_catalog.pg_namespace n, pg_catalog.pg_class c WHERE c.relnamespace = n.oid AND c.relkind IN ('r','p')`},
		{"psql \\dt (v16)", `SELECT n.nspname as "Schema", c.relname as "Name", CASE c.relkind WHEN 'r' THEN 'table' WHEN 'v' THEN 'view' END as "Type", pg_catalog.pg_get_userbyid(c.relowner) as "Owner" FROM pg_catalog.pg_class c LEFT JOIN pg_catalog.pg_namespace n ON n.oid = c.relnamespace LEFT JOIN pg_catalog.pg_am am ON am.oid = c.relam WHERE c.relkind IN ('r','p','') AND n.nspname <> 'pg_catalog' AND n.nspname !~ '^pg_toast' AND n.nspname <> 'information_schema' AND pg_catalog.pg_table_is_visible(c.oid) ORDER BY 1,2`},
		{"any", "START TRANSACTION"},
		{"any", "ROLLBACK"},
		{"any", "BEGIN ISOLATION LEVEL READ COMMITTED, READ WRITE"},
		{"any", "END"},
		{"any", "BEGIN; SELECT 1; ABORT"},
		{"Rails/Ecto/others", "LOCK TABLE users IN ACCESS EXCLUSIVE MODE"},
		{"any", "SELECT * FROM users FOR UPDATE"},
		{"queue libs (river, pgmq)", "SELECT * FROM users ORDER BY id LIMIT 1 FOR UPDATE SKIP LOCKED"},
		{"any", "CREATE SCHEMA IF NOT EXISTS app"},
		{"any", "CREATE EXTENSION IF NOT EXISTS pgcrypto"},
		{"any", "LISTEN ch"},
		{"any", "COMMENT ON TABLE users IS 'x'"},
		{"any", "ANALYZE"},
		{"any", "SELECT now()::timestamptz, 1::int4, 'a'::varchar, 1.5::numeric"},
		{"any", "SELECT CAST(1 AS bigint)"},
		{"any", "SELECT EXTRACT(EPOCH FROM now())"},
		{"any", "EXPLAIN SELECT * FROM users"},
		{"any", "SELECT * FROM users WHERE name ILIKE 'a%' AND age = ANY(ARRAY[1,2])"},
		{"any", "INSERT INTO users (name) VALUES ('b') ON CONFLICT DO NOTHING"},
		{"any", "COPY users TO STDOUT"},
	}
	fail := 0
	for _, p := range probes {
		_, err := c.PgConn().Exec(ctx, p.q).ReadAll()
		if err != nil {
			fail++
			q := p.q
			if len(q) > 90 {
				q = q[:90] + "..."
			}
			t.Logf("REJECTED [%s] %s\n      -> %s", p.tool, q, short(err))
			// leave any failed block
			c.PgConn().Exec(ctx, "ROLLBACK").ReadAll()
		}
	}
	t.Logf("%d probes, %d rejected", len(probes), fail)
}
