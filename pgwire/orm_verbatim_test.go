package pgwire_test

// Deep-look D-51: statements migration tools and drivers send, copied
// verbatim from the tools' own sources (module cache versions named on
// each test) rather than from memory, so the list says which tool needs
// which statement. Each runs through pgx over the wire, the way the tool
// would issue it (parameters as the tool binds them).
//
// Not covered here because their sources were not available to copy
// from: GORM v2 beyond HasTable (TestClientProbes), golang-migrate and
// atlas. goose's table locker (lock.NewPostgresTableLocker) needs
// `now() + $3::interval`, and bytdb has no interval type (N-048), so only
// its default migrator and session locker are listed.

import (
	"context"
	"testing"

	"github.com/jackc/pgx/v5"
)

// TestGooseVerbatim drives goose v3.27.2's Postgres dialect
// (internal/dialects/postgres.go) and session locker (lock/postgres.go)
// through one migration's life: probe the version table, create it,
// record versions, list them, and hold the advisory lock throughout.
func TestGooseVerbatim(t *testing.T) {
	ctx := context.Background()
	c := connect(t, startServer(t))
	const lockID = int64(5887940537704921958) // goose's DefaultLockID (crc64 of "goose")

	var got bool
	if err := c.QueryRow(ctx, "SELECT pg_try_advisory_lock($1)", lockID).Scan(&got); err != nil || !got {
		t.Fatalf("pg_try_advisory_lock: %v %v", got, err)
	}
	tableExists := `SELECT EXISTS ( SELECT 1 FROM pg_tables WHERE (current_schema() IS NULL OR schemaname = current_schema()) AND tablename = 'goose_db_version' )`
	var exists bool
	if err := c.QueryRow(ctx, tableExists).Scan(&exists); err != nil || exists {
		t.Fatalf("TableExists before create: %v %v", exists, err)
	}
	mustExec(t, c, `CREATE TABLE goose_db_version (
		id integer PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
		version_id bigint NOT NULL,
		is_applied boolean NOT NULL,
		tstamp timestamp NOT NULL DEFAULT now()
	)`)
	if err := c.QueryRow(ctx, tableExists).Scan(&exists); err != nil || !exists {
		t.Fatalf("TableExists after create: %v %v", exists, err)
	}
	// The schema-qualified form of the same probe.
	if err := c.QueryRow(ctx, `SELECT EXISTS ( SELECT 1 FROM pg_tables WHERE schemaname = 'public' AND tablename = 'goose_db_version' )`).Scan(&exists); err != nil || !exists {
		t.Fatalf("TableExists qualified: %v %v", exists, err)
	}
	insert := `INSERT INTO goose_db_version (version_id, is_applied) VALUES ($1, $2)`
	tx, err := c.Begin(ctx) // goose applies each migration in a transaction
	if err != nil {
		t.Fatal(err)
	}
	for _, v := range []int64{0, 20260101, 20260202} {
		if _, err := tx.Exec(ctx, insert, v, true); err != nil {
			t.Fatalf("InsertVersion %d: %v", v, err)
		}
	}
	if err := tx.Commit(ctx); err != nil {
		t.Fatal(err)
	}
	rows, err := c.Query(ctx, `SELECT version_id, is_applied from goose_db_version ORDER BY id DESC`)
	if err != nil {
		t.Fatal(err)
	}
	var versions []int64
	for rows.Next() {
		var v int64
		var applied bool
		if err := rows.Scan(&v, &applied); err != nil {
			t.Fatal(err)
		}
		versions = append(versions, v)
	}
	if rows.Err() != nil || len(versions) != 3 || versions[0] != 20260202 {
		t.Fatalf("ListMigrations: %v %v", versions, rows.Err())
	}
	var applied bool
	var tstamp any
	if err := c.QueryRow(ctx, `SELECT tstamp, is_applied FROM goose_db_version WHERE version_id=$1 ORDER BY tstamp DESC LIMIT 1`, int64(20260101)).Scan(&tstamp, &applied); err != nil || !applied {
		t.Fatalf("GetMigrationByVersion: %v %v", applied, err)
	}
	var latest int64
	if err := c.QueryRow(ctx, `SELECT max(version_id) FROM goose_db_version`).Scan(&latest); err != nil || latest != 20260202 {
		t.Fatalf("GetLatestVersion: %d %v", latest, err)
	}
	mustExec(t, c, `DELETE FROM goose_db_version WHERE version_id=$1`, int64(20260202))
	if err := c.QueryRow(ctx, "SELECT pg_advisory_unlock($1)", lockID).Scan(&got); err != nil || !got {
		t.Fatalf("pg_advisory_unlock: %v %v", got, err)
	}
}

// TestLibPQVerbatim covers lib/pq v1.12.3's connect path (conn.go): the
// startup parameters it sends (client_encoding, datestyle) and the
// probes target_session_attrs runs when the server did not report the
// answers as ParameterStatus.
func TestLibPQVerbatim(t *testing.T) {
	ctx := context.Background()
	cfg, err := pgx.ParseConfig(startServer(t))
	if err != nil {
		t.Fatal(err)
	}
	cfg.RuntimeParams["client_encoding"] = "UTF8"
	cfg.RuntimeParams["datestyle"] = "ISO, MDY"
	c, err := pgx.ConnectConfig(ctx, cfg)
	if err != nil {
		t.Fatalf("lib/pq startup parameters refused: %v", err)
	}
	defer c.Close(ctx)
	var hs bool
	if err := c.QueryRow(ctx, "select pg_catalog.pg_is_in_recovery()").Scan(&hs); err != nil || hs {
		t.Errorf("pg_is_in_recovery: %v %v", hs, err)
	}
	var ro string
	if err := c.QueryRow(ctx, "show transaction_read_only").Scan(&ro); err != nil || ro != "off" {
		t.Errorf("show transaction_read_only: %q %v", ro, err)
	}
	var ds string
	if err := c.QueryRow(ctx, "show datestyle").Scan(&ds); err != nil || ds != "ISO, MDY" {
		t.Errorf("show datestyle: %q %v", ds, err)
	}
}

// TestPgxVerbatim covers pgx v5.10.0's own statements (conn.go):
// DeallocateAll's `deallocate all`, after which the statement cache
// re-prepares transparently.
func TestPgxVerbatim(t *testing.T) {
	ctx := context.Background()
	c := connect(t, startServer(t))
	var n int64
	if err := c.QueryRow(ctx, `select $1::int8 + 1`, int64(1)).Scan(&n); err != nil || n != 2 {
		t.Fatalf("cached statement: %d %v", n, err)
	}
	if err := c.DeallocateAll(ctx); err != nil {
		t.Fatalf("DeallocateAll: %v", err)
	}
	if err := c.QueryRow(ctx, `select $1::int8 + 1`, int64(2)).Scan(&n); err != nil || n != 3 {
		t.Fatalf("after DeallocateAll: %d %v", n, err)
	}
}
